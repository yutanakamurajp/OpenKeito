//! Schedule files: values of network elements over time, such as the
//! generator outputs of an optimal power flow for every hour of a day.
//!
//! A schedule says nothing about the EMT model itself: a converter (the
//! Python package) applies its values to the network at one of its times,
//! solves the power flow and converts the result into a model.

use std::collections::HashMap;

use schemars::JsonSchema;
use serde::{Deserialize, Serialize};

use crate::diagnostic::Diagnostic;

/// Value of the `format` field of a schedule file.
pub const SCHEDULE_FORMAT: &str = "openkeito-schedule";
/// Current (and only) value of the `version` field of a schedule file.
pub const SCHEDULE_VERSION: &str = "0.1";

/// Values of network elements at a list of times.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize, JsonSchema)]
#[serde(deny_unknown_fields)]
pub struct Schedule {
    /// Must be "openkeito-schedule".
    pub format: String,
    /// Must be "0.1".
    pub version: String,
    /// Short name.
    #[serde(default)]
    pub name: String,
    /// Free text, such as where the values come from.
    #[serde(default)]
    pub description: String,
    /// How a value holds between two of the times. Default "step".
    #[serde(default)]
    pub interpolation: Interpolation,
    /// Times of the values: RFC 3339 date-times with an offset, strictly
    /// ascending, such as "2026-11-21T09:00:00+09:00" or
    /// "2026-11-21T00:00:00Z".
    pub times: Vec<String>,
    pub series: Vec<Series>,
}

/// How a value holds between two times of a schedule.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default, Serialize, Deserialize, JsonSchema)]
#[serde(rename_all = "snake_case")]
pub enum Interpolation {
    /// The value of a time holds until the next time.
    #[default]
    Step,
    /// Linear between two times (not for in_service and tap_position, which
    /// keep the earlier value).
    Linear,
}

/// The values of one quantity of one element.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize, JsonSchema)]
#[serde(deny_unknown_fields)]
pub struct Series {
    /// The element: "<table>/<index>" for pandapower, such as "gen/0" or
    /// "load/12", or the mRID of a CGMES element.
    pub target: String,
    pub quantity: ScheduledQuantity,
    /// One value per time.
    pub values: Vec<f64>,
}

/// A scheduled quantity. The unit is part of the name.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize, JsonSchema)]
#[serde(rename_all = "snake_case")]
pub enum ScheduledQuantity {
    /// Three-phase active power: generated by generators and static
    /// generators, consumed by loads and charging storage.
    ActivePowerMw,
    /// Three-phase reactive power, with the sign of the element's table.
    ReactivePowerMvar,
    /// Voltage set point of a generator or external grid, > 0.
    VoltagePu,
    /// Tap position of a transformer, an integer.
    TapPosition,
    /// 1 in service, 0 out of service.
    InService,
}

impl ScheduledQuantity {
    /// The name in schedule files.
    pub fn as_str(self) -> &'static str {
        match self {
            ScheduledQuantity::ActivePowerMw => "active_power_mw",
            ScheduledQuantity::ReactivePowerMvar => "reactive_power_mvar",
            ScheduledQuantity::VoltagePu => "voltage_pu",
            ScheduledQuantity::TapPosition => "tap_position",
            ScheduledQuantity::InService => "in_service",
        }
    }
}

/// Seconds since 1970-01-01T00:00:00Z and nanoseconds of an RFC 3339
/// date-time such as "2026-11-21T09:00:00+09:00" or
/// "2026-11-21T00:00:00.25Z". `None` if the text is not one, including a
/// date-time without an offset.
pub fn parse_date_time(s: &str) -> Option<(i64, u32)> {
    let b = s.as_bytes();
    if b.len() < 20
        || b[4] != b'-'
        || b[7] != b'-'
        || !matches!(b[10], b'T' | b't')
        || b[13] != b':'
        || b[16] != b':'
    {
        return None;
    }
    let num = |from: usize, to: usize| -> Option<i64> {
        let t = s.get(from..to)?;
        t.bytes()
            .all(|c| c.is_ascii_digit())
            .then(|| t.parse().ok())?
    };
    let (year, month, day) = (num(0, 4)?, num(5, 7)?, num(8, 10)?);
    let (hour, minute, second) = (num(11, 13)?, num(14, 16)?, num(17, 19)?);
    let mut i = 19;
    let mut nanos = 0;
    if b[i] == b'.' {
        let start = i + 1;
        i = start;
        while i < b.len() && b[i].is_ascii_digit() {
            i += 1;
        }
        let digits = i - start;
        if digits == 0 || digits > 9 {
            return None;
        }
        nanos = s[start..i].parse::<u32>().ok()? * 10u32.pow(9 - digits as u32);
    }
    let offset = match s.get(i..)? {
        "Z" | "z" => 0,
        rest if rest.len() == 6 && matches!(b[i], b'+' | b'-') && b[i + 3] == b':' => {
            let (h, m) = (num(i + 1, i + 3)?, num(i + 4, i + 6)?);
            if h > 23 || m > 59 {
                return None;
            }
            if b[i] == b'-' {
                -(h * 3600 + m * 60)
            } else {
                h * 3600 + m * 60
            }
        }
        _ => return None,
    };
    let leap = (year % 4 == 0 && year % 100 != 0) || year % 400 == 0;
    let month_days = [
        31,
        28 + i64::from(leap),
        31,
        30,
        31,
        30,
        31,
        31,
        30,
        31,
        30,
        31,
    ];
    if !(1..=12).contains(&month)
        || !(1..=month_days[(month - 1) as usize]).contains(&day)
        || hour > 23
        || minute > 59
        || second > 60
    {
        return None;
    }
    // Days since 1970-01-01 of a date of the proleptic Gregorian calendar
    // (H. Hinnant, "chrono-Compatible Low-Level Date Algorithms",
    // days_from_civil).
    let y = if month <= 2 { year - 1 } else { year };
    let era = y.div_euclid(400);
    let yoe = y - era * 400;
    let doy = (153 * ((month + 9) % 12) + 2) / 5 + day - 1;
    let doe = yoe * 365 + yoe / 4 - yoe / 100 + doy;
    let days = era * 146_097 + doe - 719_468;
    Some((
        days * 86_400 + hour * 3600 + minute * 60 + second - offset,
        nanos,
    ))
}

/// Checks a schedule file. Whether its targets exist is for the converter
/// to check against the network.
pub fn validate_schedule(s: &Schedule) -> Vec<Diagnostic> {
    let mut d = Vec::new();
    if s.format != SCHEDULE_FORMAT {
        d.push(Diagnostic::error(
            "E500",
            "format",
            format!("format is \"{}\"", s.format),
            format!("Set \"format\": \"{SCHEDULE_FORMAT}\"."),
        ));
    }
    if s.version != SCHEDULE_VERSION {
        d.push(Diagnostic::error(
            "E500",
            "version",
            format!("version \"{}\" is not supported", s.version),
            format!("Set \"version\": \"{SCHEDULE_VERSION}\"."),
        ));
    }
    if s.times.is_empty() {
        d.push(Diagnostic::error(
            "E501",
            "times",
            "the schedule has no times",
            "Give at least one time, such as \"2026-11-21T00:00:00+09:00\".",
        ));
    }
    if s.series.is_empty() {
        d.push(Diagnostic::error(
            "E501",
            "series",
            "the schedule has no series",
            "Add series as {\"target\": \"gen/0\", \"quantity\": \"active_power_mw\", \"values\": [...]}.",
        ));
    }
    let mut previous: Option<(usize, (i64, u32))> = None;
    for (k, t) in s.times.iter().enumerate() {
        match parse_date_time(t) {
            None => d.push(Diagnostic::error(
                "E502",
                format!("times[{k}]"),
                format!("\"{t}\" is not an RFC 3339 date-time with an offset"),
                "Write the date, 'T', the time and the offset, such as \
                 \"2026-11-21T09:00:00+09:00\" or \"2026-11-21T00:00:00Z\".",
            )),
            Some(at) => {
                if let Some((j, before)) = previous {
                    if at <= before {
                        d.push(Diagnostic::error(
                            "E503",
                            format!("times[{k}]"),
                            format!("\"{t}\" is not after times[{j}] (\"{}\")", s.times[j]),
                            "List every time once, in ascending order.",
                        ));
                    }
                }
                previous = Some((k, at));
            }
        }
    }
    let mut seen: HashMap<(&str, ScheduledQuantity), usize> = HashMap::new();
    for (k, series) in s.series.iter().enumerate() {
        let p = format!("series[{k}]");
        if series.target.trim().is_empty() {
            d.push(Diagnostic::error(
                "E507",
                format!("{p}.target"),
                "the target is empty",
                "Name the element, such as \"gen/0\" (pandapower table and index) or a CGMES mRID.",
            ));
        } else if let Some(first) = seen.insert((series.target.as_str(), series.quantity), k) {
            d.push(Diagnostic::error(
                "E505",
                p.clone(),
                format!(
                    "{} of \"{}\" is already given by series[{first}]",
                    series.quantity.as_str(),
                    series.target
                ),
                "Give each quantity of an element in one series.",
            ));
        }
        if series.values.len() != s.times.len() {
            d.push(Diagnostic::error(
                "E504",
                format!("{p}.values"),
                format!("{} values for {} times", series.values.len(), s.times.len()),
                "Give one value per time, in the order of times.",
            ));
        }
        for (j, &v) in series.values.iter().enumerate() {
            let bad = match series.quantity {
                ScheduledQuantity::ActivePowerMw | ScheduledQuantity::ReactivePowerMvar => {
                    (!v.is_finite()).then_some("Use a finite value.")
                }
                ScheduledQuantity::VoltagePu => (!(v.is_finite() && v > 0.0))
                    .then_some("A voltage set point must be > 0 pu, typically 0.9 to 1.1."),
                ScheduledQuantity::TapPosition => (!(v.is_finite() && v.fract() == 0.0))
                    .then_some("A tap position is an integer."),
                ScheduledQuantity::InService => {
                    (v != 0.0 && v != 1.0).then_some("Use 1 (in service) or 0 (out of service).")
                }
            };
            if let Some(hint) = bad {
                d.push(Diagnostic::error(
                    "E506",
                    format!("{p}.values[{j}]"),
                    format!(
                        "{} of \"{}\" is {v}",
                        series.quantity.as_str(),
                        series.target
                    ),
                    hint,
                ));
            }
        }
    }
    d
}

#[cfg(test)]
mod tests {
    use super::parse_date_time;

    #[test]
    fn date_times() {
        assert_eq!(parse_date_time("1970-01-01T00:00:00Z"), Some((0, 0)));
        // 2026-11-21T00:00:00Z: 20 778 days after the epoch.
        assert_eq!(
            parse_date_time("2026-11-21T09:00:00+09:00"),
            Some((20_778 * 86_400, 0))
        );
        assert_eq!(
            parse_date_time("2026-11-20T15:30:00.25-08:30"),
            Some((20_778 * 86_400, 250_000_000))
        );
        assert_eq!(
            parse_date_time("2000-02-29T12:00:00Z"),
            Some((11_016 * 86_400 + 43_200, 0))
        );
        for bad in [
            "2026-11-21T09:00:00",
            "2026-11-21 09:00:00Z",
            "2026-02-29T00:00:00Z",
            "2026-13-01T00:00:00Z",
            "2026-11-21T24:00:00Z",
            "2026-11-21T09:00:00+0900",
            "2026-11-21T09:00:00.Z",
            "2026-11-21",
        ] {
            assert_eq!(parse_date_time(bad), None, "{bad}");
        }
    }
}
